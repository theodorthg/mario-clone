def glyph_name(ch):
    return "uni%04X" % ord(ch) if ch != " " else "space"


def build():
    names = [".notdef"] + [glyph_name(c) for c in G]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({ord(c): glyph_name(c) for c in G})
    glyphs, metrics = {}, {}
    pen = TTGlyphPen(None)
    pen.moveTo((0, 0)); pen.lineTo((0, 875)); pen.lineTo((500, 875)); pen.lineTo((500, 0)); pen.closePath()
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (750, 0)
    for ch, rows in G.items():
        w = max(len(r) for r in rows)
        pen = TTGlyphPen(None)
        for ry, row in enumerate(rows):
            # row 6 is the baseline row: its bottom edge sits at y = 0
            y0 = (6 - ry) * PX
            for rx, c in enumerate(row):
                if c == "#":
                    x0 = rx * PX
                    pen.moveTo((x0, y0))
                    pen.lineTo((x0, y0 + PX))
                    pen.lineTo((x0 + PX, y0 + PX))
                    pen.lineTo((x0 + PX, y0))
                    pen.closePath()
        glyphs[glyph_name(ch)] = pen.glyph()
        adv = (w + 1) * PX if ch != " " else 4 * PX
        metrics[glyph_name(ch)] = (adv, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=875, descent=-250)
    fb.setupNameTable({"familyName": "MarioClonePixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=875, sTypoDescender=-250, usWinAscent=875, usWinDescent=250)
    fb.setupPost()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    fb.save(OUT)
    print("  %s (%d glyphs)" % (OUT, len(G)))


if __name__ == "__main__":
    build()
